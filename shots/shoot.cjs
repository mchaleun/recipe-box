const { chromium } = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright');
const path = require('path');
const url = 'file://' + path.resolve('dist-preview/index.html');
(async () => {
  const b = await chromium.launch();
  const errors = [];
  const run = async (name, vp, scheme, steps) => {
    const ctx = await b.newContext({ viewport: vp, colorScheme: scheme, deviceScaleFactor: 1, hasTouch: vp.width < 600 });
    const p = await ctx.newPage();
    p.on('pageerror', (e) => errors.push(name + ': ' + e.message));
    p.on('console', (m) => { if (m.type() === 'error') errors.push(name + ' console: ' + m.text()); });
    await p.goto(url + (steps.hash || ''));
    await p.waitForTimeout(600);
    if (steps.act) await steps.act(p);
    await p.waitForTimeout(500);
    const ow = await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    if (ow > 0) errors.push(name + ': horizontal overflow ' + ow + 'px');
    await p.screenshot({ path: `shots/${name}.png`, fullPage: !!steps.full });
    await ctx.close();
  };
  const phone = { width: 390, height: 844 }, laptop = { width: 1366, height: 860 }, ipad = { width: 1180, height: 820 };
  await run('lib-phone', phone, 'light', { full: true });
  await run('lib-laptop', laptop, 'light', {});
  await run('lib-laptop-dark', laptop, 'dark', {});
  await run('search-phone', phone, 'light', { act: async (p) => { await p.fill('#library-search', 'pumpkin'); } });
  await run('recipe-phone', phone, 'light', { hash: '#/recipe/cinnamon-rolls', full: true, act: async (p) => { await p.click('.ing >> nth=1'); await p.click('.step >> nth=0'); await p.click('[aria-label="More servings"]'); } });
  await run('recipe-laptop', laptop, 'light', { hash: '#/recipe/french-chocolate-mousse', act: async (p) => { await p.mouse.wheel(0, 700); } });
  await run('recipe-laptop-dark', laptop, 'dark', { hash: '#/recipe/berry-chantilly-cake' });
  await run('cook-phone', phone, 'light', { hash: '#/cook/sourdough-bread' });
  await run('cook-ipad', ipad, 'light', { hash: '#/cook/cream-of-whatever-soup', act: async (p) => { await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight'); await p.click('.timer-chip'); } });
  await run('cook-phone-dark-ing', phone, 'dark', { hash: '#/cook/hot-fudge', act: async (p) => { await p.click('.cook-ing-btn'); } });
  await run('edit-phone', phone, 'light', { hash: '#/edit/hot-fudge', full: true });
  await run('edit-laptop', laptop, 'dark', { hash: '#/edit/new' });
  await run('filters-phone', phone, 'light', { act: async (p) => { await p.click('.pill-btn'); } });
  await run('collections-laptop', laptop, 'light', { hash: '#/collections' });
  await run('collection-phone', phone, 'dark', { hash: '#/collections/thanksgiving' });
  await run('settings-phone', phone, 'light', { hash: '#/settings', full: true });
  console.log(errors.join('\n') || 'no errors');
  await b.close();
})();
